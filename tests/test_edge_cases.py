@pytest.mark.parametrize("top_k", [1, 5, 10])
def test_demo_dataset_various_top_k(top_k):
    resp = client.get("/demo/dataset", params={"top_k": top_k})
    assert resp.status_code == 200
    body = resp.json()
    for record in body["audit_records"]:
        rr = record.get("retrieval_result")
        if rr:
            assert len(rr["evidence"]) <= top_k


