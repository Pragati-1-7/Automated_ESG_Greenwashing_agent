# Full-dataset demo: verifies all three verdict types are actually reachable
# ---------------------------------------------------------------------------


def test_dataset_demo_produces_all_three_verdict_types():
    resp = client.get("/demo/dataset")
    assert resp.status_code == 200
    verdicts = {
        r["verification_result"]["verdict"]
        for r in resp.json()["audit_records"]
        if r.get("verification_result")
    }
    assert {"ALIGN", "CONTRADICT", "INSUFFICIENT_EVIDENCE"}.issubset(verdicts)


def test_not_checkable_claims_have_no_verification_or_risk_score():
    claims = load_dataset_claims()
    records = build_audit_records(claims, top_k=5, use_semantic=False)
    not_checkable = [
        r for r in records if r.checkability_result.checkability.value == "NOT_CHECKABLE"
    ]
    assert not_checkable, "Dataset should contain at least one NOT_CHECKABLE claim"
    for r in not_checkable:
        assert r.verification_result is None
        assert r.risk_score_result is None
        assert r.retrieval_result is None


# ---------------------------------------------------------------------------
# Unknown / missing dataset claim id at the pipeline level
# ---------------------------------------------------------------------------


def test_analyze_dataset_rejects_unknown_and_mixed_claim_ids():
    from app.api.pipeline import analyze_dataset

    with pytest.raises(PipelineError):
        analyze_dataset(claim_ids=["CLM-999-DOES-NOT-EXIST"])

    # A mix of one real + one fake id should keep only the real one.
    result = analyze_dataset(claim_ids=["CLM-001", "CLM-999-DOES-NOT-EXIST"])
    assert len(result["audit_records"]) == 1
    assert result["audit_records"][0]["claim_id"] == "CLM-001"
