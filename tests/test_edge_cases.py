"""
test_edge_cases.py

STEP 6: Edge-case and user-scenario tests for the Step 6 application layer,
using the synthetic PDFs generated by scripts/generate_edge_case_pdfs.py.

These simulate real user actions against the FastAPI backend:
  - uploading a blank/scanned PDF
  - uploading a PDF with no ESG content
  - uploading a corrupted / non-PDF file
  - uploading a renamed copy of the sample PDF (mock-mode limitation)
  - uploading a large multi-page PDF
  - boundary values for top_k
  - unknown claim lookups
  - the curated dataset demo (guaranteed ALIGN/CONTRADICT/INSUFFICIENT_EVIDENCE)

All offline, no network/API keys required.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

fastapi = pytest.importorskip("fastapi")
from fastapi.testclient import TestClient

from app.api.main import app
from app.api.pipeline import (
    PipelineError,
    analyze_pdf_file,
    build_audit_records,
    load_dataset_claims,
)

client = TestClient(app)

EDGE_CASE_DIR = PROJECT_ROOT / "data" / "sample_pdfs" / "edge_cases"


def _edge_case(name: str) -> Path:
    path = EDGE_CASE_DIR / name
    if not path.exists():
        pytest.skip(f"Run `python scripts/generate_edge_case_pdfs.py` first (missing {name})")
    return path


# ---------------------------------------------------------------------------
# User scenario: uploads a scanned/image-only report (no extractable text)
# ---------------------------------------------------------------------------


def test_blank_scanned_pdf_reports_no_extractable_text():
    path = _edge_case("blank_scanned_report.pdf")
    with path.open("rb") as f:
        resp = client.post(
            "/analyze",
            data={"use_demo": "false", "mode": "mock"},
            files={"file": ("blank_scanned_report.pdf", f, "application/pdf")},
        )
    assert resp.status_code == 200
    body = resp.json()
    assert body["status"] == "no_claims"
    assert "no extractable text" in body["message"].lower()
    assert body["summary"]["total_claims"] == 0
    # Regression: the response must echo the ORIGINAL uploaded filename, never
    # the server's internal tempfile name (found via live curl testing).
    assert body["source_document"] == "blank_scanned_report.pdf"
    assert not body["source_document"].startswith("tmp")


def test_analyze_response_echoes_original_filename_not_tempfile_name():
    """The server saves uploads to a NamedTemporaryFile before parsing; the API
    response must report the filename the user actually uploaded, not the
    server-generated temp path. Caught via live HTTP testing, not TestClient."""
    path = _edge_case("unrelated_content.pdf")
    with path.open("rb") as f:
        resp = client.post(
            "/analyze",
            data={"use_demo": "false", "mode": "mock"},
            files={"file": ("my_company_report_2025.pdf", f, "application/pdf")},
        )
    assert resp.status_code == 200
    assert resp.json()["source_document"] == "my_company_report_2025.pdf"


